-- Run in Supabase Dashboard > SQL Editor
create table if not exists public.products (
 id bigint generated by default as identity primary key,
 model text not null,
 brand text not null default 'Other',
 storage text,
 price numeric(12,2) not null check(price > 0),
 condition text not null default 'Good',
 pta_status text not null default 'Not confirmed',
 status text not null default 'available' check(status in ('available','sold')),
 image_url text,
 description text,
 created_at timestamptz not null default now()
);
create table if not exists public.remobix_admins (
 user_id uuid primary key references auth.users(id) on delete cascade
);
alter table public.products enable row level security;
alter table public.remobix_admins enable row level security;
create policy "Admin can view own membership" on public.remobix_admins for select to authenticated using (auth.uid() = user_id);
create policy "Public can view available products" on public.products for select to anon, authenticated using (status = 'available');
create policy "Admins can view all products" on public.products for select to authenticated using (exists(select 1 from public.remobix_admins a where a.user_id=auth.uid()));
create policy "Admins can insert products" on public.products for insert to authenticated with check (exists(select 1 from public.remobix_admins a where a.user_id=auth.uid()));
create policy "Admins can update products" on public.products for update to authenticated using (exists(select 1 from public.remobix_admins a where a.user_id=auth.uid())) with check (exists(select 1 from public.remobix_admins a where a.user_id=auth.uid()));
create policy "Admins can delete products" on public.products for delete to authenticated using (exists(select 1 from public.remobix_admins a where a.user_id=auth.uid()));
grant select on public.products to anon, authenticated;
grant insert, update, delete on public.products to authenticated;
grant select on public.remobix_admins to authenticated;
grant usage, select on sequence public.products_id_seq to authenticated;

